export const WRITER_FORMAT_RULES = `<format_rules>
## 禁止格式
1. ❌ 禁止冒号分段
   - 错误："他说："你好，世界。""
   - 正确：他说："你好，世界。"（使用全角冒号或直接用引号）

2. ❌ 禁止【】标记
   - 错误：【系统通知】、【任务完成】
   - 正确：用正文叙述代替标记，或用引号强调

3. ❌ 禁止 emoji 和表情符号
   - 错误：他开心地笑了😊
   - 正确：他开心地笑了

4. ❌ 禁止纯数字编号列表
   - 错误：1. 第一点 2. 第二点
   - 正确：用段落衔接，或用"首先""其次""最后"等过渡词

5. ❌ 禁止 Markdown 格式
   - 错误：**重点**、*斜体*、~~删除线~~
   - 正确：纯文本，不使用格式标记

6. ❌ 禁止过度分节
   - 错误：每 200 字一个小节
   - 正确：保持自然段落，每段 300-500 字为宜
</format_rules>`;

export const WRITER_ANTIAI_RULES = `<anti_ai_rules>
## 禁止抽象词汇
以下词汇会让文本显得空洞、缺乏细节：

1. ❌ 禁止程度副词堆砌
   - 错误：非常、极其、特别、十分、相当、异常
   - 正确：用具体描述代替（"他的手在颤抖"代替"他非常紧张"）

2. ❌ 禁止抽象名词
   - 错误：情况、问题、方面、因素、影响、作用
   - 正确：用具体事物代替（"他的剑在流血"代替"情况很糟"）

3. ❌ 禁止通用动词
   - 错误：做、搞、弄、弄、整、来、去
   - 正确：用具体动作代替（"他抽出剑"代替"他做了个动作"）

## 禁止翻译腔
以下结构是英语直译，不符合中文习惯：

1. ❌ 禁止被动句过度使用
   - 错误：他被给予了这个机会
   - 正确：有人给了他这个机会 / 他得到了这个机会

2. ❌ 禁止定语后置
   - 错误：这是最重要的决定之一
   - 正确：这是最重要的决定

3. ❌ 禁止关系从句堆叠
   - 错误：那个正在读书的女孩的书的封面的颜色
   - 正确：那个女孩正在读书，书封是蓝色的

4. ❌ 禁止介词短语过度使用
   - 错误：关于这个问题，在他看来...
   - 正确：他觉得这个问题...

## 禁止机械衔接
以下衔接方式显得生硬、缺乏自然过渡：

1. ❌ 禁止转折词堆砌
   - 错误：但是、然而、不过、可是、却
   - 正确：减少转折词，用情节自然过渡

2. ❌ 禁止因果词过度使用
   - 错误：因为...所以...、由于...因此...
   - 正确：让因果关系在情节中自然呈现

3. ❌ 禁止重复的衔接词
   - 错误：每段都以"然后"开头
   - 正确：省略衔接词，让动作自然衔接

4. ❌ 禁止僵硬的总结句
   - 错误：总之、综上所述、由此可见
   - 正确：用情节发展代替总结
</anti_ai_rules>`;

export const WRITER_PACING_RULES = `<pacing_rules>
## 看点密度（Payoff Density）
每 500-800 字至少有一个看点：

### 看点类型
1. **冲突升级**：矛盾激化、对抗升级
2. **意外转折**：意料之外、情理之中
3. **信息揭示**：秘密曝光、真相大白
4. **能力展示**：战力展现、技能炫技
5. **情感冲击**：感动、愤怒、恐惧、惊喜
6. **幽默笑点**：机智对话、尴尬场景、反转搞笑

### 看点分布检查
- ❌ 错误：1500 字无任何看点
- ✅ 正确：每 500-800 字至少一个看点

## 槽点密度（Complaint Density）
避免连续 3 个以上槽点（读者可能吐槽的点）：

### 槽点类型
1. **逻辑漏洞**：人物行为不合逻辑
2. **设定冲突**：与前文设定矛盾
3. **人物降智**：聪明角色突然变蠢
4. **剧情拖沓**：无意义的重复描写
5. **强行误会**：为了剧情需要制造不合理误会

### 槽点控制
- ❌ 错误：连续 3 个槽点以上
- ✅ 正确：槽点间隔至少 1000 字，且需后续章节补丁

## 情绪高潮间隔（Emotional Peak Interval）
每隔 1500-2500 字安排一个情绪高潮：

### 情绪高潮类型
1. **战斗高潮**：生死对决、绝境反击
2. **情感高潮**：表白、分离、重逢、牺牲
3. **悬疑高潮**：真相揭示、阴谋曝光
4. **成长高潮**：突破、觉醒、顿悟

### 情绪高潮节奏
- ❌ 错误：3000 字无情绪高潮
- ✅ 正确：每 1500-2500 字一个情绪高潮

## 信息密度控制
避免信息过载或信息不足：

### 信息过载（负面）
- 每段包含 3+ 个新设定
- 快速切换 4+ 个场景
- 引入 5+ 个新人物

### 信息不足（负面）
- 连续 2 段无新信息
- 重复描写同一细节 3+ 次
- 对话无实质推进

### 信息密度标准
- ✅ 正确：每段 1-2 个关键信息
- ✅ 正确：对话推进情节或塑造人物
- ✅ 正确：描写服务氛围或埋伏笔
</pacing_rules>`;

export const WRITER_GOLDEN_OPENING = `<golden_opening>
## 黄金开头三要素
开头 50-100 字必须包含：

### 1. 钩子（Hook）
吸引读者继续阅读的元素：

**有效钩子类型**
- **悬念钩子**："尸体躺在书房中央，但房门从内部锁死。"
- **冲突钩子**："他拔出剑，指向曾经的挚友。"
- **反差钩子**："最强大的法师，此刻正躲在柜子里发抖。"
- **人物钩子**："她从不相信命运，直到命运给她打了个电话。"
- **场景钩子**："雨已经下了七天，整座城市漂浮在水面上。"

**无效钩子类型**
- ❌ 天气描写开头："今天是个晴朗的日子..."
- ❌ 人物介绍开头："小明是一个普通的上班族..."
- ❌ 抽象哲理开头："人生就像一场旅行..."

### 2. 节奏启动（Pacing Launch）
开头节奏决定章节整体节奏：

**快节奏开头（适合动作章节）**
- 第一句就进入动作
- 50 字内建立冲突
- 100 字内出现第一个转折

**中节奏开头（适合日常章节）**
- 第一句建立场景
- 50 字内引出核心人物
- 100 字内明确章节目标

**慢节奏开头（适合情感章节）**
- 第一句建立氛围
- 50 字内引出情感主线
- 100 字内铺垫情感冲突

### 3. 信息锚点（Information Anchor）
开头需锚定读者预期：

**必要信息**
- 时间：现在 / 回忆 / 未来
- 地点：场景位置
- 人物：核心人物
- 目标：章节核心任务/冲突

**开头检查清单**
- [ ] 第一句是否有钩子？
- [ ] 50 字内是否明确时间/地点/人物？
- [ ] 100 字内是否建立章节核心冲突？
- [ ] 开头节奏是否匹配章节类型？
- [ ] 是否避免天气/自我介绍/抽象哲理开头？
</golden_opening>`;

